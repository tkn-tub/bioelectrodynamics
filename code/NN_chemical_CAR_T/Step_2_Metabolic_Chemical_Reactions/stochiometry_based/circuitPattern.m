function p = circuitPattern(neuronInputMode)
%CIRCUITPATTERN Exact diagram, projected onto its 13 named metabolites.
% T(i,j): -1 consumed, +1 produced, 0 absent from reaction j.
% S magnitudes need not be one; this is a connectivity search.
if nargin < 1, neuronInputMode = 'substrate'; end
p.name = 'delayed_rails_affine_neuron_fresh_v1';
% Interface names follow the figures. Other internal species use the name
% of their producing reaction, with r_ replaced by m_. Keep this index order
% so existing saved motif.metIndex vectors remain compatible.
p.metNames = {'m_in';'m_Ff';'m_Sf';'m_Fd';'m_D1';'m_Ff_2'; ...
    'm_Sf_2';'m_D2';'m_Sd_2';'m_c';'m_I';'m_b';'m_out'};
p.legacyMetNames = {'m_in';'m_F';'m_S';'m_P1';'m_d1';'m_F2'; ...
    'm_S2';'m_d2';'m_N2';'m_c';'m_I';'m_b';'m_out'};
p.rxnNames = {'r_Ff';'r_Fd';'r_Sf';'r_Sd';'r_I';'r_Fr'; ...
    'r_Ff_2';'r_Fd_2';'r_Sf_2';'r_Sd_2';'r_I_2';'r_Sr_2'; ...
    'r_c';'r_I1';'r_I2';'r_Nw';'r_Nb';'r_Nr'};
p.descriptions = {'fast feed / pool production'; ...
    'fast delay / rail production';'slow feed / pool production'; ...
    'slow delay / first differentiator output';'rail cancellation'; ...
    'fast rail removal';'fast feed / pool production'; ...
    'fast delay / second differentiator output'; ...
    'slow feed / pool production';'slow delay / rail production'; ...
    'rail cancellation';'slow rail removal';'counter production'; ...
    'counter reset';'counter input sequestration';'neuron weight'; ...
    'buffered neuron bias';'neuron output removal'};
p.blocks = {[1:6], [7:12], [13:15], [16:18]};
p.blockNames = {'DIFFERENTIATOR 1 (OUTPUT m_D1)'; ...
    'DIFFERENTIATOR 2 (INPUT m_D1, OUTPUT m_D2)'; ...
    'COUNTER (OUTPUT m_c, SHARED SPECIES m_I)'; ...
    'SINGLE NEURON (OUTPUT m_out)'};
inputs = {[1],[2],[1],[3],[4 5],[4], ...
    [5],[6],[5],[7],[8 9],[9],[8],[10 11],[8 11],[10],[12],[13]};
outputs = {[2],[4],[3],[5],[],[],[6],[8],[7],[9],[],[], ...
    [10],[],[],[13],[13],[]};
if strcmpi(neuronInputMode, 'activation')
    inputs{16} = []; % m_c is a regulator; supplied evidence links it to r_Nw.
elseif ~strcmpi(neuronInputMode, 'substrate')
    error('Circuit:NeuronMode', 'Unknown NEURON_INPUT_MODE: %s', neuronInputMode);
end
p.T = zeros(13,18);
for j = 1:18
    p.T(inputs{j},j) = -1;
    p.T(outputs{j},j) = 1;
end
p.neuronInputMode = lower(neuronInputMode);
end

