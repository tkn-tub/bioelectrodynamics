if ~exist('PRINT_ALLOW_XML_LOAD','var'), PRINT_ALLOW_XML_LOAD = true; end
if ~exist('PRINT_INITIALIZE_COBRA_WHEN_NEEDED','var'), PRINT_INITIALIZE_COBRA_WHEN_NEEDED = false; end
if ~exist('PRINT_SAVE_MODEL_CACHE','var'), PRINT_SAVE_MODEL_CACHE = true; end
