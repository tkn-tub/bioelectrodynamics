    error('Block7:OldTopology', ...
        ['The resolved checkpoint is:\n%s\n\n', ...
         'This printer requires TopologyVersion = five_reaction_regulated_full_v2.\n', ...
         'The checkpoint is an older or different topology.\n', ...
         'Run this exporter from the folder containing the CURRENT Block 6 MAT file ', ...
         'generated by this continuation update, or set PRINT_RESULTS_FILE to that file.\n', ...
         'The existing TXT report has not been replaced.'],b7ResultsPath);
end
