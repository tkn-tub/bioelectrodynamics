    'r_Ni','r_NiDecay','r_Na','r_NaDecay','r_Nb','r_NbDecay','r_No','r_NoDecay'};
if ismember('r_CsLeak',b7Motifs.Properties.VariableNames), b7RequiredRxns{end+1} = 'r_CsLeak'; end
b7RequiredColumns = [b7RequiredMets,b7RequiredRxns,strrep(b7RequiredRxns,'r_','dir_'), ...
    {'adapterPathIndex','m_d','m_d1','m_d2','m_X2'}];
if ~all(ismember(b7RequiredColumns,b7Motifs.Properties.VariableNames)) || ...
        ~all(isfield(b7Data,{'EC_ModelMetIDs','EC_ModelRxnIDs','InputAdapterPaths','CounterCsLeakMapped'})) || ...
        ismember('r_CsSupply',b7Motifs.Properties.VariableNames)
    error('Block7:CheckpointSchema','The resolved checkpoint is incomplete for the current topology:\n%s',b7ResultsPath);
