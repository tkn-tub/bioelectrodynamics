fprintf('%s',b7Text);
fprintf('\nSaved report: %s\n',PRINT_TXT_FILE);
clear b7Folder b7Data b7Motifs b7Selection b7LoadedModel b7Model b7Paths b7Context b7Text b7Row;
clear b7ResultsPath b7Metadata b7ExpectedTopology b7RequiredMets b7RequiredRxns b7RequiredColumns;

function path = localFindFile(filename,folder)
candidates = {char(string(filename)),fullfile(folder,char(string(filename))),which(char(string(filename)))};
for k = 1:numel(candidates)
    if ~isempty(candidates{k}) && isfile(candidates{k})
        [ok,attributes] = fileattrib(candidates{k});
        if ~ok, error('Block7:FilePath','Cannot resolve the full path of %s.',candidates{k}); end
        path = attributes.Name; return;
    end
end
error('Block7:MissingFile','Cannot find %s in the local folder or MATLAB path.',filename);
end

function model = localModel(workspaceModel,data,filename,cache,folder,allowXML,initialize,saveCache)
model = workspaceModel;
loadedFromCache = false;
if localHasModel(model)
    localCheckIdentity(model,data); % never substitute another model on mismatch
elseif isfield(data,'model') && localHasModel(data.model)
    model = data.model; localCheckIdentity(model,data);
else
    cacheCandidates = {char(string(cache)),fullfile(folder,char(string(cache))),which(char(string(cache)))};
    model = struct();
    for k = 1:numel(cacheCandidates)
        if isempty(cacheCandidates{k}) || ~isfile(cacheCandidates{k}), continue; end
        cached = load(cacheCandidates{k},'printModel');
        if isfield(cached,'printModel') && localHasModel(cached.printModel)
            % A stale cache must not silently attach descriptions to another model.
            localCheckIdentity(cached.printModel,data); model = cached.printModel;
            loadedFromCache = true; break;
        end
    end
    if ~localHasModel(model)
        if ~allowXML || exist('readCbModel','file') ~= 2
            error('Block7:MissingPrintModel', ...
                ['Full formula/name equations need the original model. Run this export after the master once, ', ...
                 'or make readCbModel and %s available. Future exports use the local print-model cache.'],filename);
        end
        if initialize
            if exist('initCobraToolbox','file') ~= 2, error('Block7:MissingCOBRA','initCobraToolbox is unavailable.'); end
            initCobraToolbox(false);
        end
        model = readCbModel(localFindFile(filename,folder));
        localCheckIdentity(model,data);
    end
end
if saveCache && ~loadedFromCache
    fields = {'S','mets','metNames','metFormulas','rxns','rxnNames','grRules','rules', ...
        'eccodes','rxnECNumbers','ecNumbers','metComps','compNames','comps'};
    printModel = struct();
    for k = 1:numel(fields)
        if isfield(model,fields{k}), printModel.(fields{k}) = model.(fields{k}); end
    end
    [cacheFolder,~,~] = fileparts(char(string(cache)));
    if isempty(cacheFolder), cacheFolder = pwd; end
    temporary = [tempname(cacheFolder),'.mat']; cleanup = onCleanup(@() localRemove(temporary));
    save(temporary,'printModel','-v7');
    [ok,msg] = movefile(temporary,cache,'f');
    if ~ok, error('Block7:CacheWrite','Could not save print-model cache: %s.',msg); end
    clear cleanup;
end
end

function yes = localHasModel(model)
yes = isstruct(model) && isscalar(model) && all(isfield(model,{'S','mets','rxns'}));
end

function localCheckIdentity(model,data)
if ~localHasModel(model), error('Block7:MissingModel','Invalid print model.'); end
[nm,nr] = size(model.S);
if numel(localText(model.mets)) ~= nm || numel(localText(model.rxns)) ~= nr
    error('Block7:ModelSize','Model.S, mets and rxns have inconsistent sizes.');
end
if isfield(data,'EC_ModelMetIDs') && ~isequal(string(data.EC_ModelMetIDs(:)),localText(model.mets))
    error('Block7:ModelMismatch','Saved metabolite IDs/order disagree with the print model.');
end
if isfield(data,'EC_ModelRxnIDs') && ~isequal(string(data.EC_ModelRxnIDs(:)),localText(model.rxns))
    error('Block7:ModelMismatch','Saved reaction IDs/order disagree with the print model.');
end
% Older compact files sometimes have only selected model dictionaries.
for field = {'Differentiator_Metabolites','Differentiator_Reactions'}
    if ~isfield(data,field{1}), continue; end
    entries = data.(field{1});
    if contains(field{1},'Metabolites'), ids = localText(model.mets); else, ids = localText(model.rxns); end
    if ~istable(entries) || ~all(ismember({'Index','ID'},entries.Properties.VariableNames)), continue; end
    idx = double(entries.Index(:));
    if any(~isfinite(idx) | idx < 1 | idx > numel(ids) | idx ~= floor(idx)) || ...
            ~isequal(string(entries.ID(:)),ids(idx))
        error('Block7:ModelMismatch','Saved annotation dictionary disagrees with the print model.');
    end
end
end

function c = localContext(model,data)
c.S = model.S; c.mets = localText(model.mets); c.rxns = localText(model.rxns);
c.metNames = c.mets; c.rxnNames = c.rxns;
if isfield(model,'metNames'), c.metNames = localText(model.metNames); end
if isfield(model,'rxnNames'), c.rxnNames = localText(model.rxnNames); end
c.formulas = strings(numel(c.mets),1); c.gpr = strings(numel(c.rxns),1);
if isfield(model,'metFormulas'), c.formulas = localText(model.metFormulas); end
if isfield(model,'grRules'), c.gpr = localText(model.grRules); end
if isfield(model,'rules') && numel(c.gpr) == numel(c.rxns)
    fallback = localText(model.rules);
    if numel(fallback) == numel(c.rxns)
        missing = strlength(strtrim(c.gpr)) == 0;
        c.gpr(missing) = fallback(missing);
    end
end
c.ec = strings(numel(c.rxns),1);
for field = {'eccodes','rxnECNumbers','ecNumbers'}
    if ~isfield(model,field{1}), continue; end
    values = model.(field{1});
    if ischar(values), values = cellstr(values); end
    if numel(values) ~= numel(c.rxns), continue; end
    for r = 1:numel(c.rxns)
        if iscell(values), value = values{r}; else, value = values(r); end
        text = localECText(value);
        matches = regexp(char(text),'(?<![\w.\-])(?:[Ee][Cc]\s*:?\s*)?([1-7]\.[0-9]+\.[0-9]+\.[0-9]+)(?![\w.\-])','tokens');
        if isempty(matches), continue; end
        found = string(cellfun(@(t) t{1},matches,'UniformOutput',false));
        prior = split(c.ec(r),'; '); prior = prior(strlength(prior) > 0);
        c.ec(r) = strjoin(unique([prior(:);found(:)],'stable'),'; ');
    end
end
if isfield(data,'Differentiator_Reactions') && istable(data.Differentiator_Reactions)
    dict = data.Differentiator_Reactions;
    for k = 1:height(dict)
        r = dict.Index(k);
        if ismember('EC',dict.Properties.VariableNames) && strlength(c.ec(r)) == 0, c.ec(r) = string(dict.EC(k)); end
        if ismember('GPR',dict.Properties.VariableNames) && strlength(c.gpr(r)) == 0, c.gpr(r) = string(dict.GPR(k)); end
    end
end
c.compLabels = strings(numel(c.mets),1);
names = strings(0,1);
if isfield(model,'compNames'), names = localText(model.compNames);
elseif isfield(model,'comps'), names = localText(model.comps); end
if isfield(model,'metComps') && numel(model.metComps) == numel(c.mets) && ~isempty(names)
    idx = double(model.metComps(:)); valid = isfinite(idx) & idx >= 1 & idx <= numel(names) & idx == floor(idx);
    c.compLabels(valid) = names(idx(valid));
end
for m = 1:numel(c.mets)
    if strlength(c.compLabels(m)) > 0, continue; end
    token = regexp(char(c.mets(m)),'\[([^\]]+)\]$','tokens','once');
    if isempty(token), token = regexp(char(c.mets(m)),'_([A-Za-z][A-Za-z0-9]*)$','tokens','once'); end
    if ~isempty(token), c.compLabels(m) = string(token{1}); end
end
if numel(c.metNames) ~= numel(c.mets) || numel(c.formulas) ~= numel(c.mets) || ...
        numel(c.rxnNames) ~= numel(c.rxns) || numel(c.gpr) ~= numel(c.rxns)
    error('Block7:AnnotationSize','Model annotation lengths do not match the model indices.');
end
end

function text = localReport(c,row,paths,data,selection,total,adapterChoice)
if ~isfield(row,'m_d') || row.m_d ~= row.m_Y1 || ~isfield(row,'m_d1') || row.m_d1 ~= row.m_Y1
    error('Block7:OutputAlias','The first output aliases m_d and m_d1 must identify Y1.');
end
if isfield(row,'m_Y2')
    if isfield(row,'m_d2') && row.m_d2 ~= row.m_Y2, error('Block7:OutputAlias','m_d2 disagrees with Y2.'); end
    row.m_d2 = row.m_Y2;
end
[metFields,metLabels,rxnFields,rxnLabels] = localRoles(row);
if ~isfield(row,'m_in'), error('Block7:MissingInput','The selected motif has no m_in field.'); end
for field = metFields
    if isfield(row,field{1}), localIndex(row.(field{1}),numel(c.mets),field{1}); end
end
for field = rxnFields
    if isfield(row,field{1}), localIndex(row.(field{1}),numel(c.rxns),field{1}); end
end
if ~isstruct(paths) || isempty(paths) || ~all(isfield(paths,{'anchorMetIdx','reactionIndices'}))
    error('Block7:MissingAdapter','Saved Block 0 adapter paths are missing or incomplete.');
end
matching = find([paths.anchorMetIdx] == row.m_in);
if isempty(matching), error('Block7:MissingAdapter','No saved cAMP adapter reaches the selected m_in.'); end
if isfield(row,'adapterPathIndex')
    if ~isfield(paths,'pathIndex'), error('Block7:MissingPathIndex','Adapter pathIndex values are missing.'); end
    chosen = find([paths.pathIndex] == row.adapterPathIndex & [paths.anchorMetIdx] == row.m_in,1);
    if isempty(chosen), error('Block7:WrongAdapter','The exact stored adapter path is unavailable.'); end
    position = find(matching == chosen,1);
else
    localIndex(adapterChoice,numel(matching),'ADAPTER_MATCH_TO_PRINT');
    position = adapterChoice; chosen = matching(position);
end
path = paths(chosen);
if isfield(path,'metaboliteIndices') && ~isempty(path.metaboliteIndices)
    pathMets = double(path.metaboliteIndices(:)).';
else
    ids = strtrim(split(string(path.metabolitePath),'->'));
    [valid,pathMets] = ismember(ids,c.mets);
    if ~all(valid), error('Block7:AdapterModelMismatch','Adapter metabolite IDs are absent from the print model.'); end
    pathMets = pathMets(:).';
end
if isempty(pathMets), error('Block7:MissingAdapter','The stored adapter metabolite path is empty.'); end
for m = pathMets, localIndex(m,numel(c.mets),'adapter metabolite'); end
if isfield(path,'metabolitePath') && strlength(string(path.metabolitePath)) > 0
    ids = strtrim(split(string(path.metabolitePath),'->'));
    if ~isequal(ids(:),c.mets(pathMets(:))), error('Block7:AdapterModelMismatch','Adapter metabolite IDs disagree with the model.'); end
end
if pathMets(end) ~= row.m_in, error('Block7:AdapterEndpoint','The adapter endpoint disagrees with m_in.'); end
if isfield(path,'inputMetIdx') && path.inputMetIdx ~= pathMets(1), error('Block7:AdapterInput','Adapter input index disagrees with its path.'); end
if isfield(path,'inputMetID') && string(path.inputMetID) ~= c.mets(pathMets(1)), error('Block7:AdapterModelMismatch','Adapter input ID disagrees with the model.'); end
if isfield(path,'anchorMetID') && string(path.anchorMetID) ~= c.mets(row.m_in), error('Block7:AdapterModelMismatch','Adapter endpoint ID disagrees with the model.'); end
rxns = double(path.reactionIndices(:)).'; dirs = ones(size(rxns));
if isfield(path,'reactionDirections') && ~isempty(path.reactionDirections)
    dirs = double(path.reactionDirections(:)).';
elseif isfield(path,'reactionPath')
    labels = strtrim(split(string(path.reactionPath),'->'));
    if numel(labels) == numel(rxns), dirs(contains(lower(labels),'(reverse)')) = -1; end
end
if numel(dirs) ~= numel(rxns) || any(~ismember(dirs,[-1 1]))
    error('Block7:AdapterDirection','Invalid saved adapter directions.');
end
for r = rxns, localIndex(r,numel(c.rxns),'adapter reaction'); end
if isfield(path,'reactionPath') && strlength(string(path.reactionPath)) > 0
    ids = strtrim(split(string(path.reactionPath),'->')); ids = regexprep(ids,'\s*\(reverse\)$','');
    if ~isequal(ids(:),c.rxns(rxns(:))), error('Block7:AdapterModelMismatch','Adapter reaction IDs disagree with the model.'); end
end
tags = containers.Map('KeyType','double','ValueType','char');
for k = 1:numel(pathMets)
    if k == 1, tag = 'cAMP input'; elseif k == numel(pathMets), tag = 'm_in'; else, tag = sprintf('adapter_%d',k-1); end
    tags = localAddTag(tags,pathMets(k),tag);
end
tags = localAddTag(tags,row.m_in,'m_in');
lines = {sprintf('\n\n############################################################\nA) cAMP INPUT ADAPTER FOR SELECTED MOTIF %d\n############################################################\n',selection)};
lines{end+1} = sprintf('Selected final motif row       : %d / %d\nMatching Block 0 paths to m_in : %d\nPrinted matching path          : %d\n',selection,total,numel(matching),position);
if isfield(path,'pathIndex'), lines{end+1} = sprintf('Stored Block 0 path index      : %d\n',path.pathIndex); end
lines{end+1} = sprintf('\nInput        : %s | %s\nFixed m_in   : %s | %s\nMetabolites  : %s\nReactions    : %s\n', ...
    c.mets(pathMets(1)),c.metNames(pathMets(1)),c.mets(row.m_in),c.metNames(row.m_in), ...
    strjoin(c.mets(pathMets),' -> '),strjoin(c.rxns(rxns),' -> '));
lines{end+1} = sprintf('\n--- Block 0 reactions ---\n');
for k = 1:numel(rxns)
    if dirs(k) == 1, direction = 'forward'; else, direction = 'reverse'; end
    r = rxns(k);
    lines{end+1} = sprintf('\n  Adapter reaction %d (%s): %s | %s\n      GPR: %s\n      EC : %s\n', ...
        k,direction,c.rxns(r),c.rxnNames(r),localAnnotated(c.gpr(r)),localAnnotated(c.ec(r)));
    lines{end+1} = localEquations(c,r,dirs(k),tags);
end
lines{end+1} = sprintf('\n\n############################################################\nB) SELECTED COMPLETE MOTIF %d OF %d\nSource: Block 6: strict cross-talk-filtered motifs\n############################################################\n',selection,total);
provenance = {'motifIndexBeforeCrossTalkFilter','motifIndexBeforeMembraneFilter', ...
    'block3_idx','block2_idx','block1_idx','nn_candidate_idx','counter_input_idx','input_pair_idx', ...
    'nn_idx','counter_idx','input_idx','adapterPathIndex','motifIndexBeforeECFilter', ...
    'RegulatoryEvidenceComplete','KineticsValidated'};
for k = 1:numel(provenance)
    f = provenance{k};
    if isfield(row,f) && isscalar(row.(f)), lines{end+1} = sprintf('%-38s : %d\n',f,row.(f)); end
end
lines{end+1} = sprintf('\n--- Metabolites ---\n');
tags = containers.Map('KeyType','double','ValueType','char');
for k = 1:numel(metFields)
    f = metFields{k}; if ~isfield(row,f), continue; end
    m = row.(f);
    lines{end+1} = sprintf('  %-64s | %-18s | %-40s | %s\n',metLabels{k},c.mets(m),c.metNames(m),localFormula(c,m));
    tags = localAddTag(tags,m,f);
end
lines{end+1} = sprintf('\n--- Reactions ---\n');
for k = 1:numel(rxnFields)
    f = rxnFields{k}; if ~isfield(row,f), continue; end
    r = row.(f); direction = 1; dirField = strrep(f,'r_','dir_');
    if isfield(row,dirField), direction = row.(dirField); end
    if ~isscalar(direction) || ~ismember(direction,[-1 1]), error('Block7:Direction','Invalid direction in %s.',dirField); end
    lines{end+1} = sprintf('\n  %-9s%-45s\n      ID  : %s\n      Name: %s\n      GPR : %s\n      EC  : %s\n', ...
        f,rxnLabels{k},c.rxns(r),c.rxnNames(r),localAnnotated(c.gpr(r)),localAnnotated(c.ec(r)));
    if direction == -1, lines{end+1} = sprintf('      Direction: reverse\n'); end
    lines{end+1} = localEquations(c,r,direction,tags);
end
if isfield(row,'r_Ni') && isfield(row,'r_Cp')
    lines{end+1} = localRegulation(c,row,data);
end
lines{end+1} = sprintf('\n############################################################\nEND OF SELECTED MOTIF %d\n############################################################\n',selection);
text = strjoin(lines,'');
end

function [mets,labels,rxns,rxnLabels] = localRoles(row)
if isfield(row,'r_S1')
    mets = {'m_in','m_M1','m_d1','m_F1_delay','m_M2','m_d2','m_c','m_Cs','m_Ni','m_Na','m_Nb','m_out', ...
        'm_PC','m_PNi','m_PNa','m_PNb','m_PNo'};
    labels = {'m_in   (Block 0 endpoint / differentiator 1 input)', ...
        'm_M1   (differentiator 1 memory species)','m_d1   (Y1: differentiator 1 output / Block 2 input)', ...
        'm_F1_delay (differentiator 1 fast branch pool)', ...
        'm_M2   (differentiator 2 intermediate)','m_d2   (Y2: differentiator 2 output / sole counter regulator)', ...
        'm_c    (counter output / NN regulator)','m_Cs   (buffered counter species)', ...
        'm_Ni   (NN input-neuron species)','m_Na   (NN upper-neuron species)', ...
        'm_Nb   (NN lower-neuron species)','m_out  (NN output)', ...
        'm_PC   (selected substrate of counter production)','m_PNi  (selected substrate of NN input production)', ...
        'm_PNa  (selected substrate of NN upper production)','m_PNb  (selected substrate of NN lower production)', ...
        'm_PNo  (selected substrate of NN output production)'};
    rxns = {'r_S1','r_S2','r_F','r_I','r_R','r_S1_2','r_S2_2','r_F2','r_I2','r_R2','r_Cp','r_Cg','r_Cr', ...
        'r_Ni','r_NiDecay','r_Na','r_NaDecay','r_Nb','r_NbDecay','r_No','r_NoDecay'};
    rxnLabels = {'(differentiator 1: X1 to M1)','(differentiator 1: M1 to Y1)', ...
        '(differentiator 1: X1 to fast F1 pool)','(differentiator 1: joint F1 and Y1 removal)', ...
        '(differentiator 1: independent F1 removal)','(differentiator 2: Y1 to M2)', ...
        '(differentiator 2: M2 to Y2)','(differentiator 2: fast Y1 to Y2)', ...
        '(differentiator 2: joint M2 and Y2 removal)','(differentiator 2: independent Y2 removal)', ...
        '(counter: C production)','(counter: consumes C and Cs)','(counter: regulated Cs removal)', ...
        '(NN: input-neuron production)','(NN: input-neuron removal)','(NN: upper-neuron production)', ...
        '(NN: upper-neuron removal)','(NN: lower-neuron production)','(NN: lower-neuron removal)', ...
        '(NN: output production)','(NN: output removal)'};
    if isfield(row,'r_CsLeak')
        rxns = [rxns(1:13),{'r_CsLeak'},rxns(14:end)];
        rxnLabels = [rxnLabels(1:13),{'(counter: basal Cs removal)'},rxnLabels(14:end)];
    end
else
    error('Block7:OldTopology','The selected row does not have the minimal differentiator reaction roles.');
end
end

function text = localEquations(c,r,direction,tags)
coefficients = full(c.S(:,r))*direction;
substrates = find(coefficients < 0); products = find(coefficients > 0);
compartments = unique(c.compLabels(coefficients ~= 0),'stable'); compartments = compartments(strlength(compartments) > 0);
if isempty(compartments), location = '(not annotated)'; else, location = char(strjoin(compartments,' <-> ')); end
text = sprintf('      Compartment(s): %s\n      Eqn   : %s  ->  %s\n      Names : %s  ->  %s\n', ...
    location,localSide(c,substrates,coefficients,tags,false),localSide(c,products,coefficients,tags,false), ...
    localSide(c,substrates,coefficients,tags,true),localSide(c,products,coefficients,tags,true));
end

function text = localSide(c,indices,coefficients,tags,useNames)
if isempty(indices), text = '(empty)'; return; end
terms = strings(numel(indices),1);
for k = 1:numel(indices)
    m = indices(k);
    if useNames, label = c.metNames(m); else, label = string(localFormula(c,m)); end
    if isKey(tags,m), label = label+"("+string(tags(m))+")"; end
    coefficient = abs(coefficients(m));
    if coefficient ~= 1, label = string(sprintf('%.15g ',coefficient))+label; end
    terms(k) = label;
end
text = char(strjoin(terms,' + '));
end

function text = localRegulation(c,row,data)
regulators = {'m_d2','m_d2','m_c','m_Ni','m_Ni','m_Na','m_Nb'};
targets = {'r_Cp','r_Cr','r_Ni','r_Na','r_Nb','r_No','r_No'};
effects = [-1 -1 1 1 1 1 1];
lines = {sprintf('\n--- Nonconsuming regulatory connections ---\n')};
for k = 1:numel(targets)
    if ~isfield(row,targets{k}) || ~isfield(row,regulators{k}), continue; end
    m = row.(regulators{k}); r = row.(targets{k}); d = 1; df = strrep(targets{k},'r_','dir_');
    if isfield(row,df), d = row.(df); end
    if effects(k) < 0, effect = 'inhibition'; else, effect = 'activation'; end
    status = 'PENDING (no supplied regulatory evidence)';
    if isfield(data,'RegulatoryEvidenceInput')
        e = data.RegulatoryEvidenceInput;
        if istable(e) && all(ismember({'MetIndex','RxnIndex','Direction','Effect','Evidence'},e.Properties.VariableNames))
            hit = e.MetIndex == m & e.RxnIndex == r & e.Direction == d & e.Effect == effects(k);
            evidence = string(e.Evidence(hit));
            evidence = evidence(~ismissing(evidence) & strlength(strtrim(evidence)) > 0);
            if ~isempty(evidence), status = char(strjoin(evidence,'; ')); end
        end
    end
    lines{end+1} = sprintf('  %-8s (%s) : %-10s (%s) | %-10s | %s\n',regulators{k},c.mets(m),targets{k},c.rxns(r),effect,status);
end
text = strjoin(lines,'');
end

function tags = localAddTag(tags,index,name)
index = double(index);
if isKey(tags,index)
    existing = split(string(tags(index)),',');
    if ~any(existing == string(name)), tags(index) = char(strjoin([existing(:);string(name)],',')); end
else
    tags(index) = name;
end
end

function localIndex(index,n,field)
if ~isnumeric(index) || ~isreal(index) || ~isscalar(index) || ~isfinite(index) || index < 1 || index > n || index ~= floor(index)
    error('Block7:ModelIndex','Field %s contains invalid index for this model.',field);
end
end

function text = localFormula(c,m)
text = c.formulas(m);
if ismissing(text) || strlength(strtrim(text)) == 0, text = c.mets(m); end
text = char(text);
end

function text = localAnnotated(value)
if ismissing(value) || strlength(strtrim(string(value))) == 0, text = '(none annotated)'; else, text = char(string(value)); end
end

function values = localText(raw)
if ischar(raw), values = string(cellstr(raw)); else, values = string(raw(:)); end
values(ismissing(values)) = ""; values = values(:);
end

function text = localECText(raw)
if iscell(raw)
    parts = strings(numel(raw),1);
    for k = 1:numel(raw), parts(k) = localECText(raw{k}); end
    text = strjoin(parts,'; ');
elseif ischar(raw) || isstring(raw)
    values = localText(raw); text = strjoin(values,'; ');
else
    text = "";
end
end

function localWriteText(filename,text)
[folder,~,~] = fileparts(char(string(filename)));
if isempty(folder), folder = pwd; end
temporary = [tempname(folder),'.txt']; cleanup = onCleanup(@() localRemove(temporary));
handle = fopen(temporary,'w','n','UTF-8');
if handle < 0, error('Block7:Write','Cannot create the temporary report.'); end
closeCleanup = onCleanup(@() fclose(handle));
fprintf(handle,'%s',text);
[writeError,errorCode] = ferror(handle);
if errorCode ~= 0, error('Block7:Write','Could not finish the report: %s.',writeError); end
clear closeCleanup;
[ok,message] = movefile(temporary,filename,'f');
if ~ok, error('Block7:Write','Could not finalize the report: %s.',message); end
clear cleanup;
end

function localRemove(filename)
if isfile(filename), delete(filename); end
end
