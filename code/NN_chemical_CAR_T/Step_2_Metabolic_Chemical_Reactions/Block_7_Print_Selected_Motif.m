if ~isscalar(b7Data.CounterCsLeakMapped) || ...
        logical(b7Data.CounterCsLeakMapped) ~= ismember('r_CsLeak',b7Motifs.Properties.VariableNames)
    error('Block7:BufferMode','Checkpoint Cs-support metadata disagree with its reaction columns.');
