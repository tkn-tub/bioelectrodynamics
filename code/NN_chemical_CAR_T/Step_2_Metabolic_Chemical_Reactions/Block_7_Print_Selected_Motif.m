% Self-contained formatter: no renderMinimalFullMotif or other helper needed.
% Uses the current minimal/Hill topology, with the layout of the TXT example.
% Older checkpoints are rejected before the model cache or TXT is written.
if ~exist('MOTIF_TO_PRINT','var'), MOTIF_TO_PRINT = 1; end
if ~exist('ADAPTER_MATCH_TO_PRINT','var'), ADAPTER_MATCH_TO_PRINT = 1; end
if ~exist('PRINT_RESULTS_FILE','var'), PRINT_RESULTS_FILE = 'Block_6_no_internal_crosstalk.mat'; end
if ~exist('PRINT_TXT_FILE','var'), PRINT_TXT_FILE = 'Block_7_Selected_Motifs.txt'; end
