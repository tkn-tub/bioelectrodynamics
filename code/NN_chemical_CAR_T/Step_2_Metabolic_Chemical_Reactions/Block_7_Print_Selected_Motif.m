fprintf('Printing checkpoint: %s\nTopology: %s\n',b7ResultsPath,b7ExpectedTopology);
b7Selection = MOTIF_TO_PRINT(:).';
if ~isnumeric(b7Selection) || ~isreal(b7Selection) || ...
        any(~isfinite(b7Selection) | b7Selection < 1 | b7Selection > height(b7Motifs) | b7Selection ~= floor(b7Selection))
